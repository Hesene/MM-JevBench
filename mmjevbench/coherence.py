"""Probability-coherence metrics for MM-JevBench.

The functions in this module compare *paired* model predictions generated by
controlled transformations.  They intentionally do not inspect gold labels:
coherence and task accuracy are separate properties and should be reported
separately.

All distribution-level errors use total-variation (TV) distance unless the
function name explicitly says ``odds``.  TV is ``0.5 * L1`` and therefore lies
in ``[0, 1]`` for valid probability distributions.  Inputs are validated so a
malformed model output cannot silently improve a benchmark score.
"""

from __future__ import annotations

from dataclasses import dataclass
from itertools import combinations
import math
from numbers import Integral, Real
from typing import Hashable, Iterable, Mapping, Sequence


__all__ = [
    "MonotonicityViolation",
    "batch_independence_distribution_error",
    "batch_independent_distribution_error",
    "candidate_permutation_alignment_error",
    "choice_merge_additivity_error",
    "logical_monotonicity_error",
    "logical_monotonicity_violation_rate",
    "logical_monotonicity_violations",
    "noul_negation_error",
    "submenu_conditional_consistency_error",
    "submenu_odds_consistency_error",
]


_DEFAULT_ATOL = 1e-8


def _probability(value: Real, *, name: str) -> float:
    """Return ``value`` as a finite probability or raise ``ValueError``."""

    if isinstance(value, bool) or not isinstance(value, Real):
        raise ValueError(f"{name} must be a real number, got {value!r}")
    result = float(value)
    if not math.isfinite(result) or not 0.0 <= result <= 1.0:
        raise ValueError(f"{name} must be finite and in [0, 1], got {value!r}")
    return result


def _distribution(
    values: Sequence[Real], *, name: str, atol: float = _DEFAULT_ATOL
) -> tuple[float, ...]:
    """Validate and copy a probability distribution."""

    if isinstance(values, (str, bytes)):
        raise ValueError(f"{name} must be a sequence of probabilities")
    try:
        result = tuple(
            _probability(value, name=f"{name}[{index}]")
            for index, value in enumerate(values)
        )
    except TypeError as exc:
        raise ValueError(f"{name} must be a sequence of probabilities") from exc
    if not result:
        raise ValueError(f"{name} must not be empty")
    if not math.isclose(sum(result), 1.0, rel_tol=0.0, abs_tol=atol):
        raise ValueError(f"{name} must sum to 1 within atol={atol}")
    return result


def _tv(left: Sequence[float], right: Sequence[float]) -> float:
    if len(left) != len(right):
        raise ValueError("distributions must have the same number of outcomes")
    return 0.5 * sum(abs(a - b) for a, b in zip(left, right))


def candidate_permutation_alignment_error(
    reference: Sequence[Real],
    permuted: Sequence[Real],
    new_to_reference: Sequence[int],
    *,
    atol: float = _DEFAULT_ATOL,
) -> float:
    """Return REP error after aligning a candidate permutation.

    ``new_to_reference[j]`` is the position in ``reference`` of the candidate
    shown at position ``j`` in ``permuted``.  For example, transforming
    ``[A, B, C]`` into ``[C, A, B]`` uses ``[2, 0, 1]``.  The returned error is
    TV distance between the reference distribution and the aligned prediction.
    """

    ref = _distribution(reference, name="reference", atol=atol)
    changed = _distribution(permuted, name="permuted", atol=atol)
    if len(ref) != len(changed):
        raise ValueError("reference and permuted must have equal length")
    if len(new_to_reference) != len(ref):
        raise ValueError("new_to_reference must have one index per candidate")

    indices: list[int] = []
    for position, index in enumerate(new_to_reference):
        if isinstance(index, bool) or not isinstance(index, Integral):
            raise ValueError(
                f"new_to_reference[{position}] must be an integer index"
            )
        indices.append(int(index))
    if sorted(indices) != list(range(len(ref))):
        raise ValueError("new_to_reference must be a permutation of 0..n-1")

    aligned = [0.0] * len(ref)
    for new_index, reference_index in enumerate(indices):
        aligned[reference_index] = changed[new_index]
    return _tv(ref, aligned)


def noul_negation_error(
    proposition: Sequence[Real],
    negated_proposition: Sequence[Real],
    *,
    atol: float = _DEFAULT_ATOL,
) -> float:
    """Return MEA complement error for paired Noul predictions.

    Noul candidate order is fixed as ``[No, Yes]`` (``[否, 是]``).  If the
    second prompt denotes the exact logical negation of the first, its coherent
    distribution is ``[proposition[1], proposition[0]]``.
    """

    positive = _distribution(proposition, name="proposition", atol=atol)
    negative = _distribution(
        negated_proposition, name="negated_proposition", atol=atol
    )
    if len(positive) != 2 or len(negative) != 2:
        raise ValueError("Noul distributions must contain exactly [No, Yes]")
    expected_negative = (positive[1], positive[0])
    return _tv(expected_negative, negative)


def _validated_partition(
    groups: Sequence[Sequence[int]], outcome_count: int
) -> tuple[tuple[int, ...], ...]:
    if not groups:
        raise ValueError("groups must not be empty")
    normalized: list[tuple[int, ...]] = []
    seen: list[int] = []
    for group_index, group in enumerate(groups):
        if isinstance(group, (str, bytes)):
            raise ValueError(f"groups[{group_index}] must contain integer indices")
        current: list[int] = []
        for index in group:
            if isinstance(index, bool) or not isinstance(index, Integral):
                raise ValueError("groups must contain only integer indices")
            current.append(int(index))
        if not current:
            raise ValueError("each merge group must contain at least one outcome")
        normalized.append(tuple(current))
        seen.extend(current)
    if sorted(seen) != list(range(outcome_count)):
        raise ValueError(
            "groups must be a disjoint, exhaustive partition of fine outcomes"
        )
    return tuple(normalized)


def choice_merge_additivity_error(
    fine_distribution: Sequence[Real],
    groups: Sequence[Sequence[int]],
    merged_distribution: Sequence[Real],
    *,
    atol: float = _DEFAULT_ATOL,
) -> float:
    """Return MEA finite-additivity error after merging Choice candidates.

    ``groups[k]`` lists fine-candidate indices represented by merged candidate
    ``k``.  Groups must form a disjoint and exhaustive partition.  The expected
    merged probability is the sum of its members; the metric is TV distance to
    the model's prediction on the merged prompt.
    """

    fine = _distribution(fine_distribution, name="fine_distribution", atol=atol)
    merged = _distribution(
        merged_distribution, name="merged_distribution", atol=atol
    )
    partition = _validated_partition(groups, len(fine))
    if len(partition) != len(merged):
        raise ValueError("merged_distribution must have one value per group")
    expected = tuple(sum(fine[index] for index in group) for group in partition)
    return _tv(expected, merged)


def _submenu_inputs(
    full_distribution: Sequence[Real],
    submenu_indices: Sequence[int],
    submenu_distribution: Sequence[Real],
    *,
    atol: float,
) -> tuple[tuple[float, ...], tuple[float, ...], tuple[int, ...]]:
    full = _distribution(full_distribution, name="full_distribution", atol=atol)
    submenu = _distribution(
        submenu_distribution, name="submenu_distribution", atol=atol
    )
    if len(submenu_indices) < 2:
        raise ValueError("a submenu must retain at least two candidates")
    indices: list[int] = []
    for position, index in enumerate(submenu_indices):
        if isinstance(index, bool) or not isinstance(index, Integral):
            raise ValueError(f"submenu_indices[{position}] must be an integer")
        normalized = int(index)
        if not 0 <= normalized < len(full):
            raise ValueError(f"submenu index {normalized} is out of range")
        indices.append(normalized)
    if len(set(indices)) != len(indices):
        raise ValueError("submenu_indices must not contain duplicates")
    if len(indices) != len(submenu):
        raise ValueError("submenu_distribution must have one value per retained index")
    return full, submenu, tuple(indices)


def submenu_conditional_consistency_error(
    full_distribution: Sequence[Real],
    submenu_indices: Sequence[int],
    submenu_distribution: Sequence[Real],
    *,
    atol: float = _DEFAULT_ATOL,
) -> float:
    """Return CHO conditional-consistency error for a restricted menu.

    The expected submenu distribution is the full-menu distribution
    conditioned on the retained candidates.  The error is TV distance.  This
    relation should only be used when deleting candidates adds no information
    and the study assumes stable relative preferences / IIA.
    """

    full, submenu, indices = _submenu_inputs(
        full_distribution, submenu_indices, submenu_distribution, atol=atol
    )
    retained_mass = sum(full[index] for index in indices)
    if retained_mass <= atol:
        raise ValueError("retained candidates have zero probability mass")
    conditional = tuple(full[index] / retained_mass for index in indices)
    return _tv(conditional, submenu)


def submenu_odds_consistency_error(
    full_distribution: Sequence[Real],
    submenu_indices: Sequence[int],
    submenu_distribution: Sequence[Real],
    *,
    atol: float = _DEFAULT_ATOL,
) -> float:
    """Return mean absolute pairwise log-odds change for a restricted menu.

    A coherent conditional restriction preserves every retained pair's odds.
    This unbounded diagnostic is zero at exact consistency and is expressed in
    natural-log units.  Because log odds are undefined at the boundary, all
    retained full-menu and submenu probabilities must be strictly positive.
    """

    full, submenu, indices = _submenu_inputs(
        full_distribution, submenu_indices, submenu_distribution, atol=atol
    )
    selected = tuple(full[index] for index in indices)
    if any(value <= 0.0 for value in selected) or any(
        value <= 0.0 for value in submenu
    ):
        raise ValueError("odds consistency requires strictly positive probabilities")

    changes = [
        abs(
            (math.log(selected[left]) - math.log(selected[right]))
            - (math.log(submenu[left]) - math.log(submenu[right]))
        )
        for left, right in combinations(range(len(indices)), 2)
    ]
    return sum(changes) / len(changes)


@dataclass(frozen=True)
class MonotonicityViolation:
    """One violated implication ``antecedent -> consequent``."""

    antecedent: Hashable
    consequent: Hashable
    gap: float


def _logical_gaps(
    yes_probabilities: Mapping[Hashable, Real],
    implications: Iterable[tuple[Hashable, Hashable]],
) -> tuple[tuple[Hashable, Hashable, float], ...]:
    if not isinstance(yes_probabilities, Mapping) or not yes_probabilities:
        raise ValueError("yes_probabilities must be a non-empty mapping")
    probabilities = {
        key: _probability(value, name=f"yes_probabilities[{key!r}]")
        for key, value in yes_probabilities.items()
    }
    relations = tuple(implications)
    if not relations:
        raise ValueError("implications must contain at least one relation")

    result: list[tuple[Hashable, Hashable, float]] = []
    for relation_index, relation in enumerate(relations):
        try:
            antecedent, consequent = relation
        except (TypeError, ValueError) as exc:
            raise ValueError(
                f"implications[{relation_index}] must be an (antecedent, consequent) pair"
            ) from exc
        if antecedent not in probabilities or consequent not in probabilities:
            raise ValueError(
                f"implication {relation!r} refers to an unknown proposition"
            )
        gap = max(0.0, probabilities[antecedent] - probabilities[consequent])
        result.append((antecedent, consequent, gap))
    return tuple(result)


def logical_monotonicity_violations(
    yes_probabilities: Mapping[Hashable, Real],
    implications: Iterable[tuple[Hashable, Hashable]],
    *,
    tolerance: float = 0.0,
) -> tuple[MonotonicityViolation, ...]:
    """Return LOG implication violations larger than ``tolerance``.

    Each pair means ``antecedent -> consequent`` under the same evidence, so
    coherence requires ``P(antecedent) <= P(consequent)``.  Returned ``gap`` is
    the full probability difference, not a tolerance-adjusted value.
    """

    if isinstance(tolerance, bool) or not isinstance(tolerance, Real):
        raise ValueError("tolerance must be a real number")
    normalized_tolerance = float(tolerance)
    if not math.isfinite(normalized_tolerance) or normalized_tolerance < 0.0:
        raise ValueError("tolerance must be finite and non-negative")
    return tuple(
        MonotonicityViolation(antecedent, consequent, gap)
        for antecedent, consequent, gap in _logical_gaps(
            yes_probabilities, implications
        )
        if gap > normalized_tolerance
    )


def logical_monotonicity_error(
    yes_probabilities: Mapping[Hashable, Real],
    implications: Iterable[tuple[Hashable, Hashable]],
) -> float:
    """Return mean positive probability gap over all tested implications."""

    gaps = _logical_gaps(yes_probabilities, implications)
    return sum(gap for _, _, gap in gaps) / len(gaps)


def logical_monotonicity_violation_rate(
    yes_probabilities: Mapping[Hashable, Real],
    implications: Iterable[tuple[Hashable, Hashable]],
    *,
    tolerance: float = 0.0,
) -> float:
    """Return the fraction of implications violated beyond ``tolerance``."""

    if isinstance(tolerance, bool) or not isinstance(tolerance, Real):
        raise ValueError("tolerance must be a real number")
    normalized_tolerance = float(tolerance)
    if not math.isfinite(normalized_tolerance) or normalized_tolerance < 0.0:
        raise ValueError("tolerance must be finite and non-negative")
    gaps = _logical_gaps(yes_probabilities, implications)
    return sum(gap > normalized_tolerance for _, _, gap in gaps) / len(gaps)


def _paired_distributions(
    independent: Sequence[Sequence[Real]] | Mapping[Hashable, Sequence[Real]],
    batched: Sequence[Sequence[Real]] | Mapping[Hashable, Sequence[Real]],
) -> tuple[tuple[Sequence[Real], Sequence[Real], str], ...]:
    independent_is_mapping = isinstance(independent, Mapping)
    batched_is_mapping = isinstance(batched, Mapping)
    if independent_is_mapping != batched_is_mapping:
        raise ValueError("independent and batched must use the same container type")

    if independent_is_mapping:
        independent_mapping = independent
        batched_mapping = batched
        if set(independent_mapping) != set(batched_mapping):
            raise ValueError("independent and batched mappings must have identical keys")
        if not independent_mapping:
            raise ValueError("at least one paired prediction is required")
        return tuple(
            (independent_mapping[key], batched_mapping[key], f"[{key!r}]")
            for key in independent_mapping
        )

    if isinstance(independent, (str, bytes)) or isinstance(batched, (str, bytes)):
        raise ValueError("independent and batched must contain distributions")
    if len(independent) != len(batched):
        raise ValueError("independent and batched must contain the same samples")
    if not independent:
        raise ValueError("at least one paired prediction is required")
    return tuple(
        (reference, batch_prediction, f"[{index}]")
        for index, (reference, batch_prediction) in enumerate(
            zip(independent, batched)
        )
    )


def batch_independent_distribution_error(
    independent: Sequence[Sequence[Real]] | Mapping[Hashable, Sequence[Real]],
    batched: Sequence[Sequence[Real]] | Mapping[Hashable, Sequence[Real]],
    *,
    reduction: str = "mean",
    atol: float = _DEFAULT_ATOL,
) -> float:
    """Return BAT error between independent and batched predictions.

    Inputs may be equally ordered sequences or mappings keyed by sample ID.
    Per-sample error is TV distance.  ``reduction`` is ``"mean"`` (the primary
    metric) or ``"max"`` (a worst-case diagnostic).
    """

    if reduction not in {"mean", "max"}:
        raise ValueError("reduction must be 'mean' or 'max'")
    errors: list[float] = []
    for reference, batch_prediction, suffix in _paired_distributions(
        independent, batched
    ):
        ref = _distribution(reference, name=f"independent{suffix}", atol=atol)
        changed = _distribution(
            batch_prediction, name=f"batched{suffix}", atol=atol
        )
        errors.append(_tv(ref, changed))
    return sum(errors) / len(errors) if reduction == "mean" else max(errors)


def batch_independence_distribution_error(
    independent: Sequence[Sequence[Real]] | Mapping[Hashable, Sequence[Real]],
    batched: Sequence[Sequence[Real]] | Mapping[Hashable, Sequence[Real]],
    *,
    reduction: str = "mean",
    atol: float = _DEFAULT_ATOL,
) -> float:
    """Spelling alias for :func:`batch_independent_distribution_error`."""

    return batch_independent_distribution_error(
        independent, batched, reduction=reduction, atol=atol
    )
